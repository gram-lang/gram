import type { DurationFailure } from "../src/duration";

/**
 * How a recipe writes a duration, language by language: the reference table of
 * `parseDuration`, also the one the docs show. A valid case gives its minutes,
 * or `[min, max]` for a range; a refused case gives the reason.
 *
 * `common` holds the international notation (clock, primes), read the same in
 * every language. Adding a language means adding its table here: the test fails
 * for a language of `TIME_DICTIONARIES` without one.
 */
export interface DurationCases {
	valid: [text: string, minutes: number | [number, number]][];
	refused: [text: string, reason: DurationFailure][];
}

